%   y(5) alpha    y(6) beta                Lagrange-multiplier functions (SM Sec. S1)
%   y(7) phi      protein area fraction    y(8) dphi/du
%   y(9) area/(2*pi) accumulated from u = 0
%   y(10) protein area/(2*pi) accumulated from u = 0
%   y(11) lambda  surface-tension multiplier
%   para = [h, lambda(0), mu]: meridian length, tension at u = 0, protein chemical potential
%
% Parameters in code units (see README): ka = kappa, C0 spontaneous curvature (0 here),
% kT, Lambda, chi, ap. pre (pressure difference), fext (axial point force) and V0
% (strength of an optional soft repulsion near the axis) are all zero in this work.
% The entropic term is replaced by its fourth-order Taylor expansion for
% phi < epsilon and phi > 1 - epsilon, epsilon = ENTROPY_CUTOFF() = 1e-4 (SM Sec. S1.5).
h = para(1);
%la = para(2);
mu = para(3);

psi = y(1,:);
dpsi = y(2,:);
r = y(3,:);
%z = y(4,:);
al = y(5,:);
be = y(6,:);
rho = y(7,:);
drho = y(8,:);
%area = y(9,:);
%Num = y(10,:);
la = y(11,:);

c0 = C0;

% V0=10;
Sp=50;
rlim=0.05;

epsilon = entropy_cutoff();       % 1e-4 in this work

fz = 0;                                                        % fz(area)
% fr=0;
fr = V0*(exp(Sp*(2*rlim-r))-1).*(u>0.05).*(u<0.95).*(r<2*rlim);                                                        % fr(area)
fu = fr.*cos(psi)-fz.*sin(psi);
fn = pre + fr.*sin(psi)+fz.*cos(psi);



dy(1,:)=dpsi;

dy(2,:)=c0.*drho.*h+(-1).*dpsi.*h.*r.^(-1).*cos(psi)+be.*h.^2.*ka.^(-1).* ...
  r.^(-1).*cos(psi)+(-1).*fext.*h.^2.*ka.^(-1).*r.^(-1).*cos(psi)+ ...
  al.*h.^2.*ka.^(-1).*r.^(-1).*sin(psi)+h.^2.*r.^(-2).*cos(psi).* ...
  sin(psi);

dy(3,:)=h.*cos(psi);

dy(4,:)=(-1).*h.*sin(psi);

dy(5,:)=ap.^(-1).*drho.^2.*h.^(-1).*Lambda+(-1).*ap.^(-1).*chi.*h.*((-1)+ ...
  rho).*rho+(1/6).*ap.^(-1).*h.*kT.*((rho)<(epsilon)).*((-3).*( ...
  (-1)+epsilon).^(-1).*epsilon.^(-1).*(epsilon+(-1).*rho).^2+(1/2).* ...
  ((-1).*((-1)+epsilon).^(-3)+epsilon.^(-3)).*(epsilon+(-1).*rho) ...
  .^4+((-1)+epsilon).^(-2).*epsilon.^(-2).*((-1)+2.*epsilon).*((-1) ...
  .*epsilon+rho).^3+(-6).*((-1)+epsilon).*log(1+(-1).*epsilon)+6.*( ...
  epsilon+(-1).*rho).*(log(1+(-1).*epsilon)+(-1).*log(epsilon))+6.* ...
  epsilon.*log(epsilon))+(1/6).*ap.^(-1).*h.*kT.*((epsilon+rho) ...
  >(1)).*((-3).*((-1)+epsilon).^(-1).*epsilon.^(-1).*((-1)+epsilon+ ...
  rho).^2+(-1).*((-1)+epsilon).^(-2).*epsilon.^(-2).*((-1)+2.* ...
  epsilon).*((-1)+epsilon+rho).^3+(1/2).*((-1).*((-1)+epsilon).^(-3) ...
  +epsilon.^(-3)).*((-1)+epsilon+rho).^4+(-6).*((-1)+epsilon).*log( ...
  1+(-1).*epsilon)+6.*((-1)+epsilon+rho).*(log(1+(-1).*epsilon)+(-1) ...
  .*log(epsilon))+6.*epsilon.*log(epsilon))+ap.^(-1).*h.*kT.*(( ...
  1+(-1).*epsilon)>=(rho)&(rho)>=(epsilon)).*((-1).*((-1)+rho).*log(1+(-1).* ...
  rho)+rho.*log(rho))+(-1).*fn.*h.*r.*sin(psi)+la.*sin(psi).*(dpsi.* ...
  r+h.*sin(psi))+h.^(-1).*ka.*r.^(-1).*(dpsi+(-1).*c0.*h.*rho).*( ...
  dpsi.*r+h.*((-1).*c0.*r.*rho+sin(psi)))+(-1/2).*h.^(-1).*ka.*r.^( ...
  -2).*(dpsi.*r+h.*((-1).*c0.*r.*rho+sin(psi))).^2+(-1).*ap.^(-1).* ...
  mu.*(h.*rho.*sin(psi).^2+r.*((-1).*drho.*cos(psi)+dpsi.*rho.*sin( ...
  psi)));

dy(6,:)=ap.^(-1).*((-1).*ap.*fn.*h.*r.*cos(psi)+h.*(ap.*la+(-1).*mu.*rho) ...
  .*cos(psi).*sin(psi)+r.*(ap.*dpsi.*la.*cos(psi)+(-1).*mu.*(dpsi.* ...
  rho.*cos(psi)+drho.*sin(psi))));

dy(7,:)=drho;

dy(8,:)=(-1/2).*ap.*h.*Lambda.^(-1).*r.^(-1).*(ap.^(-1).*h.*mu.*r+ap.^(-1) ...
  .*chi.*h.*r.*((-1)+rho)+ap.^(-1).*chi.*h.*r.*rho+2.*ap.^(-1).* ...
  drho.*Lambda.*cos(psi)+(-1/2).*ap.^(-1).*h.*kT.*r.*((epsilon+ ...
  rho)>(1)).*((-2).*((-1)+epsilon).^(-1).*epsilon.^(-1).*((-1)+ ...
  epsilon+rho)+(-1).*((-1)+epsilon).^(-2).*epsilon.^(-2).*((-1)+2.* ...
  epsilon).*((-1)+epsilon+rho).^2+(2/3).*((-1).*((-1)+epsilon).^(-3) ...
  +epsilon.^(-3)).*((-1)+epsilon+rho).^3+2.*(log(1+(-1).*epsilon)+( ...
  -1).*log(epsilon)))+(-1/2).*ap.^(-1).*h.*kT.*r.*((rho)<( ...
  epsilon)).*(2.*((-1)+epsilon).^(-1).*epsilon.^(-1).*(epsilon+(-1) ...
  .*rho)+((-1)+epsilon).^(-2).*epsilon.^(-2).*((-1)+2.*epsilon).*( ...
  epsilon+(-1).*rho).^2+(2/3).*((-1).*((-1)+epsilon).^(-3)+ ...
  epsilon.^(-3)).*((-1).*epsilon+rho).^3+2.*((-1).*log(1+(-1).* ...
  epsilon)+log(epsilon)))+ap.^(-1).*h.*kT.*r.*((1+(-1).* ...
  epsilon)>=(rho)&(rho)>=(epsilon)).*(log(1+(-1).*rho)+(-1).*log(rho))+c0.* ...
  ka.*(dpsi.*r+h.*((-1).*c0.*r.*rho+sin(psi))));

